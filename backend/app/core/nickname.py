"""
랜덤 닉네임 생성기.

가입 시 별도 닉네임이 없을 때(예: 향후 소셜 로그인) 부담 없는 기본 닉네임을 부여한다.
'형용사 + 명사' 조합이며, 모두 한글/공백만 사용해 InputValidator(1~20자, 한글·영문·숫자·공백)를 통과한다.
안드로이드 NicknameGenerator.kt와 단어 풀을 동일하게 유지한다.
"""
import random

_ADJECTIVES = [
    "떠도는", "꿈꾸는", "잠자는", "노래하는", "춤추는", "반짝이는",
    "포근한", "따스한", "살랑이는", "고요한", "산뜻한", "싱그러운",
    "웃는", "느긋한", "자유로운", "상냥한", "몽글몽글한", "나른한",
    "촉촉한", "푸른", "달콤한", "은은한",
]

_NOUNS = [
    "뭉게구름", "돌고래", "새싹", "민들레", "고양이", "수달",
    "밤하늘", "물방울", "나비", "산들바람", "이슬", "햇살",
    "파도", "개나리", "반딧불", "별빛", "다람쥐", "토끼",
    "여우", "곰돌이", "물망초", "달팽이", "구름", "제비꽃",
]


def generate_nickname() -> str:
    """'형용사 명사' 형태의 랜덤 닉네임 반환 (예: '떠도는 뭉게구름')."""
    return f"{random.choice(_ADJECTIVES)} {random.choice(_NOUNS)}"
