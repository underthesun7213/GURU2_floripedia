package com.example.plant.util

/**
 * 랜덤 닉네임 생성기 ('형용사 명사' 조합).
 * 가입 화면에서 미리 채움 + 🎲 재추첨에 사용한다.
 * 백엔드 app/core/nickname.py 와 단어 풀을 동일하게 유지한다.
 */
object NicknameGenerator {

    private val adjectives = listOf(
        "떠도는", "꿈꾸는", "잠자는", "노래하는", "춤추는", "반짝이는",
        "포근한", "따스한", "살랑이는", "고요한", "산뜻한", "싱그러운",
        "웃는", "느긋한", "자유로운", "상냥한", "몽글몽글한", "나른한",
        "촉촉한", "푸른", "달콤한", "은은한"
    )

    private val nouns = listOf(
        "뭉게구름", "돌고래", "새싹", "민들레", "고양이", "수달",
        "밤하늘", "물방울", "나비", "산들바람", "이슬", "햇살",
        "파도", "개나리", "반딧불", "별빛", "다람쥐", "토끼",
        "여우", "곰돌이", "물망초", "달팽이", "구름", "제비꽃"
    )

    /** '형용사 명사' 형태의 랜덤 닉네임 반환 (예: "떠도는 뭉게구름"). */
    fun generate(): String = "${adjectives.random()} ${nouns.random()}"
}
